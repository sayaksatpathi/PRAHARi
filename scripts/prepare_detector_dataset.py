"""Build a YOLO-format person-detection dataset from MOT17, with the reported
sequences held out.

The one rule this script exists to enforce: **the sequences Prahari reports
metrics on are never used for training.** `scripts/evaluate.py --mot ...
--max-sequences 2` takes the first two in sorted order, MOT17-02 and MOT17-04, and
every committed detection figure comes from those. Fine-tuning on them and then
reporting on them would make every number meaningless while looking like a large
improvement - which is exactly how that mistake survives review.

So the split is by sequence and stated in the output:

    HELD OUT (reported)  MOT17-02, MOT17-04
    TRAIN                MOT17-05, MOT17-09, MOT17-10, MOT17-11
    VAL                  MOT17-13

Validation is also a whole sequence rather than a random frame sample. Frames
within a sequence are nearly identical; a random split would put frame 41 in
training and frame 42 in validation, and the validation loss would then measure
memorisation and fall reassuringly while generalisation went nowhere.

    python scripts/prepare_detector_dataset.py
    # then, on a free GPU:
    yolo detect train data=datasets/mot_det/data.yaml model=yolov8n.pt imgsz=640
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

# The sequences every committed metric is measured on. Training on these would
# invalidate the entire before/after comparison.
HELD_OUT = ("MOT17-02", "MOT17-04")
# One whole sequence for validation, for the reason in the docstring.
VAL = ("MOT17-13",)


def prepare(mot_root: Path, out_dir: Path, stride: int, min_visibility: float) -> int:
    import cv2

    from prahari.eval.mot import load_gt

    sequences = sorted(d for d in mot_root.iterdir()
                       if (d / "gt" / "gt.txt").exists() and (d / "img1").is_dir())
    if not sequences:
        print(f"No MOT sequences under {mot_root}")
        return 1

    def role(seq: Path) -> str | None:
        stem = seq.name.rsplit("-", 1)[0]
        if stem in HELD_OUT:
            return None                       # never used for training
        return "val" if stem in VAL else "train"

    counts = {"train": [0, 0], "val": [0, 0]}     # [images, boxes]
    used: dict[str, list[str]] = {"train": [], "val": [], "held_out": []}

    for split in ("train", "val"):
        (out_dir / "images" / split).mkdir(parents=True, exist_ok=True)
        (out_dir / "labels" / split).mkdir(parents=True, exist_ok=True)

    for seq in sequences:
        split = role(seq)
        if split is None:
            used["held_out"].append(seq.name)
            print(f"  {seq.name:<20} HELD OUT - reported metrics come from this")
            continue
        used[split].append(seq.name)

        gt = load_gt(seq / "gt" / "gt.txt", min_visibility=min_visibility)
        images = boxes = 0
        for frame_index in sorted(gt):
            if frame_index % stride:
                continue
            src = seq / "img1" / f"{frame_index:06d}.jpg"
            if not src.exists():
                continue
            image = cv2.imread(str(src))
            if image is None:
                continue
            h, w = image.shape[:2]

            lines = []
            for entry in gt[frame_index]:
                x1, y1, x2, y2 = entry["bbox"]
                x1, y1 = max(0.0, x1), max(0.0, y1)
                x2, y2 = min(float(w), x2), min(float(h), y2)
                if x2 - x1 < 4 or y2 - y1 < 8:
                    continue
                # YOLO format: class cx cy bw bh, all normalised.
                lines.append(f"0 {((x1 + x2) / 2) / w:.6f} {((y1 + y2) / 2) / h:.6f} "
                             f"{(x2 - x1) / w:.6f} {(y2 - y1) / h:.6f}")
            if not lines:
                continue

            stem = f"{seq.name}_{frame_index:06d}"
            shutil.copyfile(src, out_dir / "images" / split / f"{stem}.jpg")
            (out_dir / "labels" / split / f"{stem}.txt").write_text("\n".join(lines))
            images += 1
            boxes += len(lines)

        counts[split][0] += images
        counts[split][1] += boxes
        print(f"  {seq.name:<20} {split:<5} {images:>5} images, {boxes:>6} boxes")

    (out_dir / "data.yaml").write_text(
        f"# MOT17 person detection, generated by scripts/prepare_detector_dataset.py\n"
        f"# HELD OUT of training (Prahari reports on these): {', '.join(used['held_out'])}\n"
        f"path: {out_dir.resolve().as_posix()}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"nc: 1\n"
        f"names: [person]\n")

    (out_dir / "split.json").write_text(json.dumps({
        "held_out_reported": used["held_out"],
        "train": used["train"],
        "val": used["val"],
        "stride": stride,
        "min_visibility": min_visibility,
        "counts": {"train": {"images": counts["train"][0], "boxes": counts["train"][1]},
                   "val": {"images": counts["val"][0], "boxes": counts["val"][1]}},
        "rule": ("Sequences Prahari reports metrics on are excluded from "
                 "training. Validation is a whole sequence, not a random frame "
                 "sample: frames within a sequence are near-identical, so a "
                 "random split measures memorisation."),
    }, indent=2))

    print(f"\n  train {counts['train'][0]} images / {counts['train'][1]} boxes")
    print(f"  val   {counts['val'][0]} images / {counts['val'][1]} boxes")
    print(f"  held out: {', '.join(used['held_out'])} - never seen in training")
    print(f"\n  {out_dir / 'data.yaml'}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mot", type=Path, default=Path("datasets/MOT17/train"))
    parser.add_argument("--out", type=Path, default=Path("datasets/mot_det"))
    parser.add_argument("--stride", type=int, default=3,
                        help="keep every Nth frame (default 3); consecutive "
                             "frames are near-duplicates")
    parser.add_argument("--min-visibility", type=float, default=0.25)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    return prepare(args.mot, args.out, args.stride, args.min_visibility)


if __name__ == "__main__":
    raise SystemExit(main())
